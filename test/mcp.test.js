import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {Store} from '../src/store.js';
import {replyMessage, sendMessage} from '../src/messaging.js';

test('MCP uses Codex metadata to identify the sender and can reply to a human', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'serein-mcp-test-'));
  const store = new Store(dir);
  const space = store.spaces()[0];
  store.addMember(space.id, {threadId: 'thread-real', name: 'agent'});
  for (let n = 0; n < 35; n++) store.addMember(space.id, {threadId: `service-${n}`, name: `service-${n}`, role: 'backend'});
  const original = store.createMessage({spaceId: space.id, sender: {id: 'human', name: 'human'}, recipient: {id: 'thread-real', name: 'agent'}, body: 'question'});
  const script = fileURLToPath(new URL('../src/mcp-server.js', import.meta.url));
  const child = spawn(process.execPath, ['--disable-warning=ExperimentalWarning', script], {env: {...process.env, SEREIN_HOME: dir}, stdio: ['pipe', 'pipe', 'pipe']});
  const responses = new Map();
  let buffer = '';
  child.stdout.on('data', chunk => {
    buffer += chunk;
    const lines = buffer.split('\n');
    buffer = lines.pop();
    for (const line of lines) {
      const message = JSON.parse(line);
      const resolve = responses.get(message.id);
      if (resolve) { responses.delete(message.id); resolve(message); }
    }
  });
  let id = 0;
  function request(method, params) {
    return new Promise((resolve, reject) => {
      const requestId = ++id;
      const timer = setTimeout(() => reject(new Error('MCP response timed out')), 5000);
      responses.set(requestId, value => { clearTimeout(timer); resolve(value); });
      child.stdin.write(`${JSON.stringify({jsonrpc: '2.0', id: requestId, method, params})}\n`);
    });
  }
  t.after(() => { child.kill(); store.close(); rmSync(dir, {recursive: true, force: true}); });
  const init = await request('initialize', {protocolVersion: '2025-03-26'});
  assert.equal(init.result.serverInfo.name, 'anle');
  const toolNames = (await request('tools/list', {})).result.tools.map(tool => tool.name);
  for (const name of ['request_review', 'list_reviews', 'get_review', 'submit_review']) assert.ok(toolNames.includes(name));
  const noIdentity = await request('tools/call', {name: 'list_members', arguments: {space_id: space.id}});
  assert.equal(noIdentity.result.isError, true);
  const found = await request('tools/call', {name: 'list_members', arguments: {space_id: space.id, query: 'backend', limit: 5}, _meta: {threadId: 'thread-real'}});
  const page = JSON.parse(found.result.content[0].text);
  assert.equal(page.total, 35);
  assert.equal(page.members.length, 5);
  assert.equal(page.next_offset, 5);
  const presence = await request('tools/call', {name: 'update_presence', arguments: {space_id: space.id, task: 'Implementing login', status: 'working'}, _meta: {threadId: 'thread-real'}});
  assert.equal(presence.result.isError, undefined);
  assert.equal(JSON.parse(presence.result.content[0].text).task_status, 'working');
  store.recordSessionObservations([{id: 'thread-real', status: {type: 'active'}}]);
  const byTask = await request('tools/call', {name: 'list_members', arguments: {space_id: space.id, query: 'login'}, _meta: {threadId: 'service-1'}});
  const matching = JSON.parse(byTask.result.content[0].text).members;
  assert.equal(matching.length, 1);
  assert.equal(matching[0].current_task, 'Implementing login');
  assert.ok(matching[0].task_updated_at);
  assert.equal(matching[0].codex_status.state, 'busy');
  const unauthorizedPresence = await request('tools/call', {name: 'update_presence', arguments: {space_id: space.id, task: 'spoof'}, _meta: {threadId: 'thread-other'}});
  assert.equal(unauthorizedPresence.result.isError, true);
  const reply = await request('tools/call', {name: 'reply_message', arguments: {space_id: space.id, reply_to: original.id, message: 'TEST_OK'}, _meta: {threadId: 'thread-real'}});
  assert.equal(reply.result.isError, undefined);
  assert.equal(store.messages(space.id).at(-1).body, 'TEST_OK');
  const question = await request('tools/call', {name: 'send_message', arguments: {space_id: space.id, to: 'human', message: 'Need a decision', reply_expected: true}, _meta: {threadId: 'thread-real'}});
  const questionId = JSON.parse(question.result.content[0].text).id;
  const status = () => request('tools/call', {name: 'get_message_status', arguments: {space_id: space.id, message_id: questionId}, _meta: {threadId: 'thread-real'}});
  let state = JSON.parse((await status()).result.content[0].text);
  assert.equal(state.delivery, 'delivered');
  assert.equal(state.reply_expected, true);
  assert.equal(state.reply, 'waiting');
  const unrelated = await request('tools/call', {name: 'get_message_status', arguments: {space_id: space.id, message_id: questionId}, _meta: {threadId: 'service-1'}});
  assert.equal(unrelated.result.isError, true);
  await replyMessage(store, {spaceId: space.id, senderId: 'human', replyTo: questionId, body: 'Approved'}, async () => {});
  state = JSON.parse((await status()).result.content[0].text);
  assert.equal(state.reply, 'replied');
  const queue = async () => {};
  const root = await sendMessage(store, {spaceId: space.id, senderId: 'thread-real', to: 'service-0', body: 'Root question'}, queue);
  const escalationResult = await request('tools/call', {name: 'send_message', arguments: {space_id: space.id, to: 'human', message: 'Private escalation', context_message_id: root.id, reply_expected: true}, _meta: {threadId: 'service-0'}});
  assert.equal(escalationResult.result.isError, undefined);
  const escalation = store.message(JSON.parse(escalationResult.result.content[0].text).id);
  assert.equal(escalation.conversation_id, root.id);
  assert.equal(escalation.parent_message_id, root.id);
  assert.equal(escalation.reply_expected, 1);
  await replyMessage(store, {spaceId: space.id, senderId: 'human', replyTo: escalation.id, body: 'Private decision'}, queue);
  await replyMessage(store, {spaceId: space.id, senderId: 'service-0', replyTo: root.id, body: 'Final answer'}, queue);
  const threadFor = threadId => request('tools/call', {name: 'get_conversation', arguments: {space_id: space.id, message_id: root.id}, _meta: {threadId}});
  const frontThread = JSON.parse((await threadFor('thread-real')).result.content[0].text);
  assert.equal(frontThread.conversation_id, root.id);
  assert.deepEqual(frontThread.messages.map(message => message.body), ['Root question', 'Final answer']);
  const backendThread = JSON.parse((await threadFor('service-0')).result.content[0].text);
  assert.equal(backendThread.messages.length, 4);
  assert.equal((await threadFor('service-1')).result.isError, true);
  const wrongContext = await request('tools/call', {name: 'send_message', arguments: {space_id: space.id, to: 'human', message: 'Not my context', context_message_id: root.id}, _meta: {threadId: 'service-1'}});
  assert.equal(wrongContext.result.isError, true);
  const wrongThread = await request('tools/call', {name: 'send_message', arguments: {space_id: space.id, to: 'human', message: 'spoof'}, _meta: {threadId: 'thread-other'}});
  assert.equal(wrongThread.result.isError, true);
});
